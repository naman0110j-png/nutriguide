/**
 * Generates supabase/seed.sql from the TypeScript seed (single source of truth).
 * Usage: npm run db:seed-sql
 */
import fs from "node:fs";
import path from "node:path";
import { seedKnowledgeBase } from "../src/data/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v: string[], type = "text") => `array[${v.map(q).join(",")}]::${type}[]`;

export function buildSeedSql(): string {
  const kb = seedKnowledgeBase();
  const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.", "begin;"];

  for (const s of kb.sources) {
    out.push(`insert into evidence_sources (id,title,url,publisher,source_type,retrieved_at,published_at,reviewed_at,review_status,claims_supported,notes) values (${[q(s.id), q(s.title), q(s.url), q(s.publisher), q(s.source_type), q(s.retrieved_at), q(s.published_at), q(s.reviewed_at), q(s.review_status), j(s.claims_supported), q(s.notes)].join(",")});`);
  }
  for (const p of kb.products) {
    out.push(`insert into products (id,brand,product_family,variant_name,category,flavour,pack_size,age_min_months,age_max_months,age_guidance_text,ingredients,nutrient_data,allergen_data,official_instructions,warnings,description,official_url,image_url,source_type,last_fetched_at,last_reviewed_at,reviewed_by,review_status,recommendation_eligible,active,field_status,conflicts,notes,source_ids,created_at,updated_at) values (${[
      q(p.id), q(p.brand), q(p.product_family), q(p.variant_name), q(p.category), q(p.flavour), q(p.pack_size), q(p.age_min_months), q(p.age_max_months), q(p.age_guidance_text),
      j(p.ingredients), j(p.nutrient_data), j(p.allergen_data), j(p.official_instructions), j(p.warnings), q(p.description), q(p.official_url), q(p.image_url), q(p.source_type),
      q(p.last_fetched_at), q(p.last_reviewed_at), q(p.reviewed_by), q(p.review_status), q(p.recommendation_eligible), q(p.active), j(p.field_status), j(p.conflicts), j(p.notes), arr(p.source_ids), q(p.created_at), q(p.updated_at),
    ].join(",")});`);
    for (const sid of p.source_ids) {
      out.push(`insert into product_evidence (product_id,evidence_source_id,field_supported,claim_supported,review_status) values (${q(p.id)},${q(sid)},'record',null,'approved');`);
    }
  }
  for (const r of kb.recipes) {
    out.push(`insert into recipes (id,name,description,age_min_months,age_max_months,meal_types,ingredients,preparation_steps,prep_time_minutes,cook_time_minutes,difficulty,allergens,dietary_tags,food_groups,textures,concern_tags,nutritional_information,benefit_description,substitutions,caveats,source_status,source_ids,source_notes,review_status,active,created_at,updated_at) values (${[
      q(r.id), q(r.name), q(r.description), q(r.age_min_months), q(r.age_max_months), arr(r.meal_types), j(r.ingredients), j(r.preparation_steps), q(r.prep_time_minutes), q(r.cook_time_minutes), q(r.difficulty),
      arr(r.allergens), arr(r.dietary_tags), arr(r.food_groups), arr(r.textures), arr(r.concern_tags, "concern_type"), "null", q(r.benefit_description), j(r.substitutions), j(r.caveats), q(r.source_status), arr(r.source_ids), q(r.source_notes), q(r.review_status), q(r.active), q(r.created_at), q(r.updated_at),
    ].join(",")});`);
  }
  for (const rp of kb.recipeProducts) {
    out.push(`insert into recipe_products (id,recipe_id,product_id,use_description,validated_quantity,quantity_unit,usage_constraints,evidence_source_id,review_status,conflict_notes) values (${[q(rp.id), q(rp.recipe_id), q(rp.product_id), q(rp.use_description), q(rp.validated_quantity), q(rp.quantity_unit), j(rp.usage_constraints), q(rp.evidence_source_id), q(rp.review_status), q(rp.conflict_notes)].join(",")});`);
  }
  for (const c of kb.concernCatalog) {
    out.push(`insert into concern_catalog (id,name,description,type,risk_level,professional_review_required,education_topics) values (${[q(c.id), q(c.name), q(c.description), q(c.type), q(c.risk_level), q(c.professional_review_required), arr(c.education_topics)].join(",")});`);
  }
  for (const e of kb.education) {
    out.push(`insert into concern_education (id,concern_type,title,educational_content,food_guidance,missing_information_questions,recommended_next_steps,referral_conditions,evidence_source_ids,review_status) values (${[q(e.id), q(e.concern_type), q(e.title), j(e.educational_content), j(e.food_guidance), j(e.missing_information_questions), j(e.recommended_next_steps), j(e.referral_conditions), arr(e.evidence_source_ids), q(e.review_status)].join(",")});`);
  }
  for (const r of kb.concernProductRules) {
    out.push(`insert into concern_product_rules (id,concern_type,product_id,relationship_type,intended_purpose,eligibility_conditions,exclusion_conditions,parent_facing_explanation,evidence_source_id,review_status) values (${[q(r.id), q(r.concern_type), q(r.product_id), q(r.relationship_type), q(r.intended_purpose), j(r.eligibility_conditions), j(r.exclusion_conditions), q(r.parent_facing_explanation), q(r.evidence_source_id), q(r.review_status)].join(",")});`);
  }
  for (const r of kb.recommendationRules) {
    out.push(`insert into recommendation_rules (id,name,description,conditions,effects,output_type,required_review_status,review_status) values (${[q(r.id), q(r.name), q(r.description), j(r.conditions), j(r.effects), q(r.output_type), q(r.required_review_status), q(r.review_status)].join(",")});`);
  }
  out.push("-- nutrient_references intentionally left empty (no validated, reviewed dataset).");
  out.push("commit;");
  return out.join("\n") + "\n";
}

if (process.argv[1] && process.argv[1].endsWith("generate-seed-sql.ts")) {
  const file = path.join(__dirname, "..", "supabase", "seed.sql");
  fs.writeFileSync(file, buildSeedSql());
  console.log(`Wrote ${file}`);
}
